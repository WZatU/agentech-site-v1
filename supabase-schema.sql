create table if not exists public.agentech_accounts (
  email text primary key,
  password_hash text not null,
  salt text not null,
  created_at timestamptz not null default now(),
  verified_at timestamptz not null default now()
);

create table if not exists public.agentech_verification_codes (
  email text primary key,
  code text not null,
  expires_at timestamptz not null,
  created_at timestamptz not null default now()
);

create table if not exists public.agentech_counters (
  key text primary key,
  value integer not null default 0,
  updated_at timestamptz not null default now()
);

insert into public.agentech_counters (key, value)
values ('children_enrolled', 0)
on conflict (key) do nothing;

create table if not exists public.agentech_preorder_invoices (
  id bigint generated by default as identity primary key,
  invoice_number text not null unique,
  product text not null,
  email text not null,
  name text not null,
  phone text not null,
  company text,
  notes text,
  status text not null default 'invoice_email_pending',
  online_payment_accepted boolean not null default false,
  created_at timestamptz not null default now()
);

alter table public.agentech_accounts enable row level security;
alter table public.agentech_verification_codes enable row level security;
alter table public.agentech_counters enable row level security;
alter table public.agentech_preorder_invoices enable row level security;
